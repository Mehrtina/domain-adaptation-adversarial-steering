"""
PSNR, SSIM, RMSE, MSE, MAE, and RS analysis for adversarial examples.

This script computes perceptual-quality statistics between clean preprocessed
model inputs and adversarial inputs generated by FGSM and PGD.

It also recomputes clean/adversarial MSE, RMSE, MAE, RS, and threshold exceedance
rates to verify consistency with the manuscript tables.

Assumptions used in the manuscript:
- Test images are defined by TEST_IMAGE_DIR in config.py
- Ground-truth labels are defined by TEST_LABEL_CSV in config.py
- Ground-truth steering angles are in degrees
- Model outputs are in radians
- Attack loss uses radians
- Predictions are converted to degrees for MSE, RMSE, MAE, and RS reporting
- Attacks are applied in normalized YUV model-input space [0,1]
- All outputs go to RESULTS_DIR / "perceptual_quality"
"""

